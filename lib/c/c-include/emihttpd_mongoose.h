/*
 * emihttpd_mongoose.h - Mongoose backend of the C server runtime
 * (`emi c --tags mongoose-server`). Works wherever Mongoose does: macOS,
 * Linux, Windows and ESP-IDF. The generated action headers only talk to the
 * port declared in emihttpd_core.h; this file implements it on top of
 * Mongoose's event loop.
 *
 * Mongoose itself is not shipped here (it is GPLv2 / commercially licensed,
 * see https://mongoose.ws): put mongoose.c and mongoose.h next to this file.
 *
 *   struct mg_mgr mgr;
 *   mg_mgr_init(&mgr);
 *   EmiHttpdRouter router;
 *   emihttpd_router_init(&router, &mgr);          // also enables mg_wakeup()
 *   my_action_register(&router, handler, NULL);   // generated, one per action
 *   emihttpd_listen(&router, "http://0.0.0.0:8000");
 *   for (;;) mg_mgr_poll(&mgr, 100);
 *
 * Threading: Mongoose is single threaded. Handlers run on the thread that
 * calls mg_mgr_poll(). Websocket sends (send/broadcast of a generated
 * action) may be called from any thread: they are queued with mg_wakeup()
 * and written by the event loop, so they return once queued.
 *
 * Text transport (`--tags text-router`, emitext.h is then next to this file): the same routes also answer a line of
 * text, ":::get /api/device", read from a serial port, a USB endpoint or a BLE characteristic, see emitext.h:
 *
 *   EmiTextLink link;
 *   emihttpd_text_link_init(&link, &router, my_write, my_user, 0);   // 0: no limit on a write
 *   emitext_link_feed(&link, bytes, n);                              // from the loop thread, as bytes arrive
 *   char* frame = emihttpd_text_call(&router, "get /api/device");    // or one call, in process (free() it)
 *
 * Generated by the Emi compiler - do not edit by hand.
 */
