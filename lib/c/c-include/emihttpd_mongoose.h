#include "emihttpd_core.h"

/* Routes one router can hold (-DEMIHTTPD_MAX_ROUTES=n for more). A route over the limit is refused: the register
 * function returns NULL and this prints a line, so the missing route is not a mystery. */
#ifndef EMIHTTPD_MAX_ROUTES
#define EMIHTTPD_MAX_ROUTES 64
#endif

struct EmiHttpdRouter;

typedef struct EmiHttpdReq {
    struct mg_connection* c;
    struct mg_http_message* hm;
} emihttpd_req_t;

typedef int (*emihttpd_serve_fn)(emihttpd_req_t* req, void* ctx);

/* kind lets the event handler tell a router (listener side) from a route (a
 * connection upgraded to websocket keeps its route in c->fn_data). */
typedef struct EmiHttpdRoute {
    int kind; /* 2 */
    EmiHttpdMethod method;
    const char* tmpl;
    bool ws;
    bool removed;
    emihttpd_serve_fn serve;
    EmiHttpdWsHooks hooks;
    void* ctx;
    struct EmiHttpdRouter* router;
} EmiHttpdRoute;

typedef struct EmiHttpdRouter {
    int kind; /* 1 */
    struct mg_mgr* mgr;
    EmiHttpdRoute* routes[EMIHTTPD_MAX_ROUTES];
    size_t count;
    /* Called for requests no route matches (e.g. to serve static files with
     * mg_http_serve_dir). Without it they get a JSON 404. */
    void (*fallback)(struct mg_connection* c, struct mg_http_message* hm, void* user);
    void* fallback_user;
} EmiHttpdRouter;

typedef EmiHttpdRouter* emihttpd_server_t;

static inline bool emihttpd_mg_method_is(const struct mg_str m, const char* name) {
    return m.len == strlen(name) && memcmp(m.buf, name, m.len) == 0;
}

static inline bool emihttpd_mg_method_matches(EmiHttpdMethod method, const struct mg_str m) {
    switch (method) {
        case EMIHTTPD_POST: return emihttpd_mg_method_is(m, "POST");
        case EMIHTTPD_PUT: return emihttpd_mg_method_is(m, "PUT");
        case EMIHTTPD_PATCH: return emihttpd_mg_method_is(m, "PATCH");
        case EMIHTTPD_DELETE: return emihttpd_mg_method_is(m, "DELETE");
        case EMIHTTPD_HEAD: return emihttpd_mg_method_is(m, "HEAD");
        case EMIHTTPD_OPTIONS: return emihttpd_mg_method_is(m, "OPTIONS");
        default: return emihttpd_mg_method_is(m, "GET");
    }
}

static inline EmiHttpdRoute* emihttpd_mg_find(EmiHttpdRouter* router, struct mg_http_message* hm) {
    for (size_t i = 0; i < router->count; i++) {
        EmiHttpdRoute* r = router->routes[i];
        if (r->removed || !emihttpd_mg_method_matches(r->method, hm->method)) continue;
        if (emihttpd_path_capture_n(r->tmpl, hm->uri.buf, hm->uri.len, NULL, 0, NULL)) return r;
    }
    return NULL;
}

/* ---- the event handler ------------------------------------------------------------------ */

static inline void emihttpd_mg_event(struct mg_connection* c, int ev, void* ev_data) {
    if (c->fn_data == NULL) return;
    EmiHttpdRoute* ws_route = NULL;
    EmiHttpdRouter* router;
    if (*(int*) c->fn_data == 2) {
        ws_route = (EmiHttpdRoute*) c->fn_data;
        router = ws_route->router;
    } else {
        router = (EmiHttpdRouter*) c->fn_data;
    }

    if (ev == MG_EV_HTTP_MSG && !ws_route) {
        struct mg_http_message* hm = (struct mg_http_message*) ev_data;
        EmiHttpdRoute* route = emihttpd_mg_find(router, hm);
        emihttpd_req_t req;
        req.c = c;
        req.hm = hm;
        if (!route) {
            if (router->fallback) {
                router->fallback(c, hm, router->fallback_user);
            } else {
                mg_http_reply(c, 404, "Content-Type: application/json\r\n", "{\"error\":\"not found\"}");
            }
        } else if (route->ws) {
            if (mg_http_get_header(hm, "Sec-WebSocket-Key") == NULL) {
                mg_http_reply(c, 426, "", "websocket expected\n");
                return;
            }
            if (route->hooks.open && route->hooks.open(&req, (emihttpd_conn_t) c->id, route->ctx) != 0) {
                mg_http_reply(c, 403, "", "rejected\n");
                return;
            }
            c->fn_data = route; /* from now on the connection belongs to the route */
            mg_ws_upgrade(c, hm, NULL);
        } else {
            route->serve(&req, route->ctx);
        }
    } else if (ev == MG_EV_WS_MSG && ws_route) {
        struct mg_ws_message* wm = (struct mg_ws_message*) ev_data;
        int op = wm->flags & 15;
        if ((op == WEBSOCKET_OP_TEXT || op == WEBSOCKET_OP_BINARY) && ws_route->hooks.message &&
            wm->data.len <= EMIHTTPD_WS_MAX_MESSAGE) {
            uint8_t* copy = (uint8_t*) calloc(1, wm->data.len + 1); /* NUL terminated for the text handlers */
            if (copy) {
                memcpy(copy, wm->data.buf, wm->data.len);
                ws_route->hooks.message((emihttpd_conn_t) c->id, op == WEBSOCKET_OP_BINARY, copy, wm->data.len, ws_route->ctx);
                free(copy);
            }
        }
    } else if (ev == MG_EV_CLOSE && ws_route) {
        if (ws_route->hooks.close) ws_route->hooks.close((emihttpd_conn_t) c->id, ws_route->ctx);
    } else if (ev == MG_EV_WAKEUP && ws_route && c->is_websocket) {
        /* queued by emihttpd_ws_write() from another thread: [op][payload] */
        struct mg_str* d = (struct mg_str*) ev_data;
        if (d->len >= 1) mg_ws_send(c, d->buf + 1, d->len - 1, (unsigned char) d->buf[0]);
    }
}

/* Prepares a router on a manager; call once, after mg_mgr_init(). */
static inline int emihttpd_router_init(EmiHttpdRouter* router, struct mg_mgr* mgr) {
    memset(router, 0, sizeof(*router));
    router->kind = 1;
    router->mgr = mgr;
    return mg_wakeup_init(mgr) ? 0 : -1;
}

/* Starts listening, e.g. "http://0.0.0.0:8000". Returns the listener or NULL. */
static inline struct mg_connection* emihttpd_listen(EmiHttpdRouter* router, const char* url) {
    return mg_http_listen(router->mgr, url, emihttpd_mg_event, router);
}

/* ---- port: routes ------------------------------------------------------------------------ */

static inline EmiHttpdRoute* emihttpd_mg_add(emihttpd_server_t router, EmiHttpdMethod method, const char* tmpl, bool ws) {
    if (router->count >= EMIHTTPD_MAX_ROUTES) {
        fprintf(stderr, "emihttpd: no room for the route %s (EMIHTTPD_MAX_ROUTES is %d)\n", tmpl, EMIHTTPD_MAX_ROUTES);
        return NULL;
    }
    EmiHttpdRoute* r = (EmiHttpdRoute*) calloc(1, sizeof(*r));
    if (!r) return NULL;
    r->kind = 2;
    r->method = method;
    r->tmpl = tmpl;
    r->ws = ws;
    r->router = router;
    router->routes[router->count++] = r;
    return r;
}

static inline void* emihttpd_add_route(emihttpd_server_t router, EmiHttpdMethod method, const char* tmpl,
                                       emihttpd_serve_fn serve, void* ctx) {
    EmiHttpdRoute* r = emihttpd_mg_add(router, method, tmpl, false);
    if (!r) return NULL;
    r->serve = serve;
    r->ctx = ctx;
    return r;
}

static inline void* emihttpd_add_ws_route(emihttpd_server_t router, const char* tmpl, const EmiHttpdWsHooks* hooks, void* ctx) {
    EmiHttpdRoute* r = emihttpd_mg_add(router, EMIHTTPD_GET, tmpl, true);
    if (!r) return NULL;
    r->hooks = *hooks;
    r->ctx = ctx;
    return r;
}

/* The route stays allocated (open connections may still point at it) but no
 * longer matches. */
static inline void emihttpd_remove_route(emihttpd_server_t router, void* route) {
    (void) router;
    if (route) ((EmiHttpdRoute*) route)->removed = true;
}

/* ---- port: reading the request ------------------------------------------------------------ */

static inline bool emihttpd_req_capture(emihttpd_req_t* req, const char* tmpl, char** out, size_t max, size_t* count) {
    return emihttpd_path_capture_n(tmpl, req->hm->uri.buf, req->hm->uri.len, out, max, count);
}

static inline char* emihttpd_req_query(emihttpd_req_t* req) {
    if (req->hm->query.len == 0) return NULL;
    char* qs = (char*) malloc(req->hm->query.len + 1);
    if (!qs) return NULL;
    memcpy(qs, req->hm->query.buf, req->hm->query.len);
    qs[req->hm->query.len] = '\0';
    return qs;
}

/* 0 on success (an empty body gives an empty string), -1 when above EMIHTTPD_MAX_BODY, -2 out of memory. */
static inline int emihttpd_req_body(emihttpd_req_t* req, char** out) {
    *out = NULL;
    if (req->hm->body.len > EMIHTTPD_MAX_BODY) return -1;
    char* buf = (char*) malloc(req->hm->body.len + 1);
    if (!buf) return -2;
    if (req->hm->body.len > 0) memcpy(buf, req->hm->body.buf, req->hm->body.len);
    buf[req->hm->body.len] = '\0';
    *out = buf;
    return 0;
}

/* ---- port: answering ------------------------------------------------------------------------ */

static inline int emihttpd_reply_json(emihttpd_req_t* req, int status, const char* json) {
    /* an answer with no body is not a json one: a client which reads the body of "application/json" would fail on it */
    mg_http_reply(req->c, status, json ? "Content-Type: application/json\r\n" : "", "%s", json ? json : "");
    return 0;
}

static inline int emihttpd_reply_error(emihttpd_req_t* req, int status, const char* msg) {
    mg_http_reply(req->c, status, "Content-Type: application/json\r\n", "{\"error\":\"%s\"}", msg ? msg : "");
    return 0;
}

/* ---- port: websocket frames ------------------------------------------------------------------ */

/* Queues a frame for a connection; safe from any thread. 0 once queued - a
 * connection that is gone is reported through the action's on_close instead. */
static inline int emihttpd_ws_write(emihttpd_server_t router, emihttpd_conn_t conn, bool binary, const uint8_t* data, size_t len) {
    unsigned char* msg = (unsigned char*) malloc(len + 1);
    if (!msg) return -1;
    msg[0] = (unsigned char) (binary ? WEBSOCKET_OP_BINARY : WEBSOCKET_OP_TEXT);
    if (len > 0) memcpy(msg + 1, data, len);
    bool ok = mg_wakeup(router->mgr, (unsigned long) conn, msg, len + 1);
    free(msg);
    return ok ? 0 : -1;
}

