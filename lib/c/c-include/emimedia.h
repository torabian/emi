/*
 * emimedia.h - the tiny per-frame header used to multiplex microphone and
 * camera data over ONE binary websocket. Twin of emigo.MediaFrame (Go),
 * emi::EmiMediaFrameHeader (C++) and MediaFrame.ts (JS) - all agree on:
 *
 *    offset  size  field
 *      0      1    kind       1 = audio, 2 = video, 3 = other
 *      1      1    flags      bit0 = keyframe
 *      2      2    reserved   0
 *      4      4    seq        per kind, big endian (a gap = a dropped frame)
 *      8      4    timestamp  milliseconds since the stream started, big endian
 *     12      n    payload    codec bytes as produced (PCM16LE, Opus, JPEG, H.264 ...)
 *
 * The codec is announced once through the action's typed query parameters.
 *
 * Generated by the Emi compiler - do not edit by hand.
 */
#ifndef EMISDK_EMIMEDIA_H
#define EMISDK_EMIMEDIA_H

#include "emiws.h"

#define EMIMEDIA_AUDIO 1
#define EMIMEDIA_VIDEO 2
#define EMIMEDIA_OTHER 3
#define EMIMEDIA_KEYFRAME 0x01
#define EMIMEDIA_HEADER_SIZE 12

typedef struct EmiMediaHeader {
    uint8_t kind;
    uint8_t flags;
    uint32_t seq;
    uint32_t timestamp_ms;
} EmiMediaHeader;

static inline void emimedia_header_write(const EmiMediaHeader* h, uint8_t out[EMIMEDIA_HEADER_SIZE]) {
    int i;
    out[0] = h->kind;
    out[1] = h->flags;
    out[2] = 0;
    out[3] = 0;
    for (i = 0; i < 4; i++) out[4 + i] = (uint8_t) (h->seq >> (8 * (3 - i)));
    for (i = 0; i < 4; i++) out[8 + i] = (uint8_t) (h->timestamp_ms >> (8 * (3 - i)));
}

/* Returns 0, or -1 when `len` is shorter than a header. */
static inline int emimedia_header_read(const uint8_t* data, size_t len, EmiMediaHeader* out) {
    int i;
    if (len < EMIMEDIA_HEADER_SIZE) return -1;
    out->kind = data[0];
    out->flags = data[1];
    out->seq = 0;
    out->timestamp_ms = 0;
    for (i = 0; i < 4; i++) out->seq = (out->seq << 8) | data[4 + i];
    for (i = 0; i < 4; i++) out->timestamp_ms = (out->timestamp_ms << 8) | data[8 + i];
    return 0;
}

/* Numbers frames per kind so the receiver can detect drops. */
typedef struct EmiMediaSender {
    EmiWebSocket* ws;
    uint32_t audio_seq;
    uint32_t video_seq;
} EmiMediaSender;

static inline void emimedia_sender_init(EmiMediaSender* s, EmiWebSocket* ws) {
    s->ws = ws;
    s->audio_seq = 0;
    s->video_seq = 0;
}

static inline int emimedia_send(EmiWebSocket* ws, const EmiMediaHeader* h, const uint8_t* payload, size_t len) {
    uint8_t prefix[EMIMEDIA_HEADER_SIZE];
    emimedia_header_write(h, prefix);
    return emiws_send_binary2(ws, prefix, sizeof(prefix), payload, len);
}

static inline int emimedia_send_audio(EmiMediaSender* s, const uint8_t* data, size_t len, uint32_t timestamp_ms) {
    EmiMediaHeader h = { EMIMEDIA_AUDIO, 0, s->audio_seq++, timestamp_ms };
    return emimedia_send(s->ws, &h, data, len);
}

static inline int emimedia_send_video(EmiMediaSender* s, const uint8_t* data, size_t len, uint32_t timestamp_ms, int keyframe) {
    EmiMediaHeader h = { EMIMEDIA_VIDEO, (uint8_t) (keyframe ? EMIMEDIA_KEYFRAME : 0), s->video_seq++, timestamp_ms };
    return emimedia_send(s->ws, &h, data, len);
}

#endif /* EMISDK_EMIMEDIA_H */
