/* A handler which returns NULL with a status >= 400 can say why: emihttpd_set_error("kind must be mqtt, post or
 * websocket") just before returning. The reply then carries that text instead of "request failed" (it is used
 * once, by the reply of that same request). One slot, no locking: the backends run the handlers of a server on one
 * thread. */
#ifndef EMIHTTPD_ERROR_MAX
#define EMIHTTPD_ERROR_MAX 160
#endif
static inline char* emihttpd_error_slot(void) {
    static char slot[EMIHTTPD_ERROR_MAX];
    return slot;
}
static inline void emihttpd_set_error(const char* message) {
    char* slot = emihttpd_error_slot();
    snprintf(slot, EMIHTTPD_ERROR_MAX, "%s", message ? message : "");
    for (char* p = slot; *p; p++) { /* it goes into a json string as it is */
        if (*p == '"' || *p == '\\') *p = '\'';
        else if ((unsigned char) *p < 0x20) *p = ' ';
    }
}
/* The text a handler set (and forgets it), else the fallback. The result is valid until the next call. */
static inline const char* emihttpd_take_error(const char* fallback) {
    static char taken[EMIHTTPD_ERROR_MAX];
    char* slot = emihttpd_error_slot();
    if (!*slot) return fallback;
    memcpy(taken, slot, EMIHTTPD_ERROR_MAX);
    slot[0] = '\0';
    return taken;
}

