/*
 * emihttpd_core.h - the server-independent half of the C server runtime
 * (`emi c --tags esp-server` or `--tags mongoose-server`): url template
 * matching, percent decoding, status lines and the websocket client registry.
 * A backend header (emihttpd_esp.h / emihttpd_mongoose.h) defines the mutex
 * primitives, includes this file and implements the "port" the generated
 * action headers are written against:
 *
 *   emihttpd_server_t / emihttpd_req_t                  the backend's types
 *   emihttpd_add_route / emihttpd_add_ws_route          register a handler
 *   emihttpd_remove_route
 *   emihttpd_req_capture / _query / _body               read the request
 *   emihttpd_reply_json / emihttpd_reply_error          answer it
 *   emihttpd_ws_write                                   push a websocket frame
 *
 * Generated by the Emi compiler - do not edit by hand.
 */
