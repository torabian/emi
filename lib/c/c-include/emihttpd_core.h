/* ---- url matching ---------------------------------------------------------- */

static inline size_t emihttpd_path_length(const char* uri) {
    size_t n = 0;
    while (uri[n] && uri[n] != '?' && uri[n] != '#') n++;
    return n;
}

/* Walks a template ("/users/:id/posts") and a request path segment by
 * segment. `:name` segments match any non-empty segment; when `out` is given
 * the (percent-decoded, malloc'd) values are stored in order, `*count` of them.
 * Returns true on a full match. On a mismatch everything captured so far is
 * freed again. */
static inline bool emihttpd_path_capture_n(const char* tmpl, const char* uri, size_t uri_len,
                                           char** out, size_t max, size_t* count) {
    size_t found = 0;
    const char* t = tmpl;
    const char* u = uri;
    const char* u_end = uri + uri_len;
    bool ok = true;

    while (ok) {
        if (*t == '/') t++;
        if (u < u_end && *u == '/') u++;
        if (*t == '\0' && u >= u_end) break;
        if (*t == '\0' || u >= u_end) { ok = false; break; }

        const char* t_end = t;
        while (*t_end && *t_end != '/') t_end++;
        const char* u_seg = u;
        while (u_seg < u_end && *u_seg != '/') u_seg++;

        if (*t == ':') {
            if (u_seg == u) { ok = false; break; }
            if (out) {
                if (found >= max) { ok = false; break; }
                size_t n = (size_t) (u_seg - u);
                char* v = (char*) malloc(n + 1);
                if (!v) { ok = false; break; }
                memcpy(v, u, n);
                v[n] = '\0';
                emihttpd_percent_decode(v, false);
                out[found] = v;
            }
            found++;
        } else if ((size_t) (t_end - t) != (size_t) (u_seg - u) || strncmp(t, u, (size_t) (t_end - t)) != 0) {
            ok = false;
            break;
        }
        t = t_end;
        u = u_seg;
    }

    if (!ok && out) {
        for (size_t i = 0; i < found && i < max; i++) { free(out[i]); out[i] = NULL; }
        found = 0;
    }
    if (count) *count = found;
    return ok;
}

/* Matches a request uri (query string allowed) against a template and
 * captures the `:placeholder` values, see emihttpd_path_capture_n. */
static inline bool emihttpd_path_capture(const char* tmpl, const char* uri, char** out, size_t max, size_t* count) {
    return emihttpd_path_capture_n(tmpl, uri, emihttpd_path_length(uri), out, max, count);
}

/* Drop-in for httpd_config_t.uri_match_fn - lets handlers be registered with
 * their emi url verbatim, "/users/:id" included. */
static inline bool emihttpd_uri_match(const char* uri_template, const char* uri_to_match, size_t match_upto) {
    size_t len = emihttpd_path_length(uri_to_match);
    if (match_upto < len) len = match_upto;
    return emihttpd_path_capture_n(uri_template, uri_to_match, len, NULL, 0, NULL);
}

/* ---- decoding ---------------------------------------------------------------- */

static inline int emihttpd_hex(char c) {
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

/* In-place %xx decoding; `plus_is_space` is for query strings. */
static inline void emihttpd_percent_decode(char* s, bool plus_is_space) {
    char* w = s;
    for (char* r = s; *r; r++) {
        if (*r == '%' && emihttpd_hex(r[1]) >= 0 && emihttpd_hex(r[2]) >= 0) {
            *w++ = (char) ((emihttpd_hex(r[1]) << 4) | emihttpd_hex(r[2]));
            r += 2;
        } else if (plus_is_space && *r == '+') {
            *w++ = ' ';
        } else {
            *w++ = *r;
        }
    }
    *w = '\0';
}

static inline bool emihttpd_parse_bool(const char* v) {
    return v && (strcmp(v, "1") == 0 || strcasecmp(v, "true") == 0 || strcasecmp(v, "yes") == 0 || strcasecmp(v, "on") == 0);
}

/* ---- query string ---------------------------------------------------------------- */

/* Returns the decoded value of `key` (malloc'd) from a raw query string, or NULL when absent.
 * Keys are compared decoded, so nested names like "filter[status]" match "filter%5Bstatus%5D". */
static inline char* emihttpd_query_get(const char* qs, const char* key) {
    if (!qs) return NULL;
    const char* p = qs;
    while (*p) {
        const char* amp = strchr(p, '&');
        size_t seg = amp ? (size_t) (amp - p) : strlen(p);
        const char* eq = (const char*) memchr(p, '=', seg);
        size_t klen = eq ? (size_t) (eq - p) : seg;
        char name[96];
        if (klen < sizeof(name)) {
            memcpy(name, p, klen);
            name[klen] = '\0';
            emihttpd_percent_decode(name, true);
            if (strcmp(name, key) == 0) {
                size_t vlen = eq ? seg - klen - 1 : 0;
                char* out = (char*) malloc(vlen + 1);
                if (!out) return NULL;
                if (vlen) memcpy(out, eq + 1, vlen);
                out[vlen] = '\0';
                emihttpd_percent_decode(out, true);
                return out;
            }
        }
        if (!amp) break;
        p = amp + 1;
    }
    return NULL;
}

/* ---- status lines ------------------------------------------------------------------- */

static inline const char* emihttpd_status_line(int code) {
    switch (code) {
        case 200: return "200 OK";
        case 201: return "201 Created";
        case 202: return "202 Accepted";
        case 204: return "204 No Content";
        case 301: return "301 Moved Permanently";
        case 302: return "302 Found";
        case 304: return "304 Not Modified";
        case 400: return "400 Bad Request";
        case 401: return "401 Unauthorized";
        case 403: return "403 Forbidden";
        case 404: return "404 Not Found";
        case 405: return "405 Method Not Allowed";
        case 408: return "408 Request Timeout";
        case 409: return "409 Conflict";
        case 413: return "413 Payload Too Large";
        case 415: return "415 Unsupported Media Type";
        case 422: return "422 Unprocessable Entity";
        case 429: return "429 Too Many Requests";
        case 500: return "500 Internal Server Error";
        case 501: return "501 Not Implemented";
        case 503: return "503 Service Unavailable";
        default: return code >= 400 ? "500 Internal Server Error" : "200 OK";
    }
}


/* ---- websocket client registry ----------------------------------------------------- */

typedef struct EmiHttpdClients {
    emihttpd_conn_t conns[EMIHTTPD_MAX_CLIENTS];
    void* ctx[EMIHTTPD_MAX_CLIENTS];
    bool used[EMIHTTPD_MAX_CLIENTS];
    emihttpd_mutex_t lock;      /* guards the tables */
    emihttpd_mutex_t send_lock; /* serialises frames written to sockets */
} EmiHttpdClients;

static inline int emihttpd_clients_init(EmiHttpdClients* c) {
    memset(c, 0, sizeof(*c));
    if (emihttpd_mutex_init(&c->lock) != 0) return -1;
    if (emihttpd_mutex_init(&c->send_lock) != 0) { emihttpd_mutex_destroy(&c->lock); return -1; }
    return 0;
}

static inline void emihttpd_clients_deinit(EmiHttpdClients* c) {
    emihttpd_mutex_destroy(&c->lock);
    emihttpd_mutex_destroy(&c->send_lock);
}

/* Stores (conn, ctx); an existing entry for the conn is replaced. 0 on success, -1 when full. */
static inline int emihttpd_clients_add(EmiHttpdClients* c, emihttpd_conn_t conn, void* ctx) {
    int rc = -1;
    emihttpd_mutex_lock(&c->lock);
    for (int i = 0; i < EMIHTTPD_MAX_CLIENTS && rc != 0; i++) {
        if (c->used[i] && c->conns[i] == conn) { c->ctx[i] = ctx; rc = 0; }
    }
    for (int i = 0; i < EMIHTTPD_MAX_CLIENTS && rc != 0; i++) {
        if (!c->used[i]) { c->used[i] = true; c->conns[i] = conn; c->ctx[i] = ctx; rc = 0; }
    }
    emihttpd_mutex_unlock(&c->lock);
    return rc;
}

static inline void* emihttpd_clients_find(EmiHttpdClients* c, emihttpd_conn_t conn) {
    void* found = NULL;
    emihttpd_mutex_lock(&c->lock);
    for (int i = 0; i < EMIHTTPD_MAX_CLIENTS; i++) {
        if (c->used[i] && c->conns[i] == conn) { found = c->ctx[i]; break; }
    }
    emihttpd_mutex_unlock(&c->lock);
    return found;
}

/* Removes the entry and hands its ctx back (NULL if the conn was not registered). */
static inline void* emihttpd_clients_remove(EmiHttpdClients* c, emihttpd_conn_t conn) {
    void* found = NULL;
    emihttpd_mutex_lock(&c->lock);
    for (int i = 0; i < EMIHTTPD_MAX_CLIENTS; i++) {
        if (c->used[i] && c->conns[i] == conn) { found = c->ctx[i]; c->used[i] = false; c->ctx[i] = NULL; break; }
    }
    emihttpd_mutex_unlock(&c->lock);
    return found;
}

/* Copies the registered conns into `conns`, returns how many. */
static inline size_t emihttpd_clients_snapshot(EmiHttpdClients* c, emihttpd_conn_t* conns, size_t max) {
    size_t n = 0;
    emihttpd_mutex_lock(&c->lock);
    for (int i = 0; i < EMIHTTPD_MAX_CLIENTS && n < max; i++) {
        if (c->used[i]) conns[n++] = c->conns[i];
    }
    emihttpd_mutex_unlock(&c->lock);
    return n;
}

