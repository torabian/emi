/* A blob as base64 text (a new string, free() it), for a text file or a json string. */
static inline char* emipack_to_base64(const uint8_t* data, size_t len) {
    static const char tbl[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    char* out = (char*) malloc(((len + 2) / 3) * 4 + 1);
    if (!out) return NULL;
    char* o = out;
    for (size_t i = 0; i < len; i += 3) {
        uint32_t v = (uint32_t) data[i] << 16;
        if (i + 1 < len) v |= (uint32_t) data[i + 1] << 8;
        if (i + 2 < len) v |= data[i + 2];
        *o++ = tbl[(v >> 18) & 63];
        *o++ = tbl[(v >> 12) & 63];
        *o++ = i + 1 < len ? tbl[(v >> 6) & 63] : '=';
        *o++ = i + 2 < len ? tbl[v & 63] : '=';
    }
    *o = '\0';
    return out;
}

/* base64 text of `n` characters back to bytes (a new buffer, free() it). Non-zero if it is not base64. */
static inline int emipack_from_base64(const char* text, size_t n, uint8_t** out, size_t* len) {
    uint8_t* buf = (uint8_t*) malloc(n / 4 * 3 + 3);
    if (!buf) return -1;
    size_t o = 0;
    uint32_t acc = 0;
    int bits = 0;
    for (size_t i = 0; i < n; i++) {
        char ch = text[i];
        int v;
        if (ch >= 'A' && ch <= 'Z') v = ch - 'A';
        else if (ch >= 'a' && ch <= 'z') v = ch - 'a' + 26;
        else if (ch >= '0' && ch <= '9') v = ch - '0' + 52;
        else if (ch == '+') v = 62;
        else if (ch == '/') v = 63;
        else if (ch == '=') break;
        else { free(buf); return -1; }
        acc = (acc << 6) | (uint32_t) v;
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            buf[o++] = (uint8_t) (acc >> bits);
        }
    }
    *out = buf;
    *len = o;
    return 0;
}

