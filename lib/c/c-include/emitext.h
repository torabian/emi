/*
 * emitext.h - the text transport of the C server runtime (`emi c --tags mongoose-server,text-router`).
 *
 * The same actions an http server answers can be called with a line of text, over anything which moves bytes: a
 * serial port (UART, USB CDC), a USB bulk / HID endpoint, a BLE GATT characteristic, a pipe. The wire format is the
 * request line of http, on one line:
 *
 *   :::METHOD[#id] /path?query [json body]\n          request   :::get /api/device
 *   :::STATUS[#id] [json body]\n                      response  :::200 {"data":{...}}
 *
 *   - METHOD is get, post, put, patch, delete, head or options (any case). `routes` instead of a method lists the
 *     routes the device has: :::routes  ->  :::200 [{"method":"GET","path":"/api/device"},...]
 *   - #id is optional (1..16 of A-Za-z0-9_-): the response carries the same id, so a client can keep requests in
 *     flight and match the answers. Without it, answers come in the order of the requests.
 *   - the path and the query are percent encoded (a space is %20): the line ends at the first newline.
 *   - the body is one line of json (compact json has no newline; the answer is made one line, too).
 *   - a line which does not start with ":::" is not ours and is skipped: a serial port also carries the log of the
 *     firmware, and a request can follow it. The status is the http status (404 no such route, 405 wrong method,
 *     400 unreadable line, 413 line too long).
 *
 * The routes are the ones registered on the http router (the generated *_register functions): the text transport has
 * no routes of its own and no authentication, so give it only to a link which is already trusted (a cable, a paired
 * peer). A websocket (`method: reactive`) action is not served over text (501).
 *
 * This file knows nothing of a transport: a link takes bytes in (emitext_link_feed, or emitext_link_message when
 * the transport has messages: a USB bulk transfer, a GATT write) and gives bytes out through the write callback, in
 * pieces of at most `mtu` bytes (a BLE notification, a USB packet; 0 = in one piece). The backend header
 * (emihttpd_mongoose.h) dispatches the request to the router.
 *
 * Generated by the Emi compiler - do not edit by hand.
 */
#ifndef EMISDK_EMITEXT_H
#define EMISDK_EMITEXT_H

#include <ctype.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifndef EMITEXT_PREFIX
#define EMITEXT_PREFIX ":::"
#endif

/* The longest line (method, path, query, body) a link buffers; a longer one is answered with 413 and dropped. */
#ifndef EMITEXT_MAX_LINE
#define EMITEXT_MAX_LINE (EMIHTTPD_MAX_BODY + 512)
#endif

/* Longest request id. */
#define EMITEXT_ID_MAX 16

/* ---- profiles of the transports -------------------------------------------------------------------------------- */

/* Serial and USB CDC-ACM: the line protocol as it is; a terminal program works as a client. 115200 8N1 is the usual.
 *
 * USB, vendor class (a device which is not a serial port): one interface with a bulk OUT endpoint (the host writes a
 * request) and a bulk IN endpoint (the device answers); every transfer is one message (emitext_link_message), the
 * answer goes out in packets of the endpoint size (mtu = 64 full speed, 512 high speed).
 *
 * BLE: one GATT service with two characteristics. The client writes requests to RX (write / write without response,
 * pieces of any size up to the ATT MTU, the newline ends a request) and subscribes to TX (notify): the answer comes
 * as notifications of at most ATT_MTU - 3 bytes (mtu = that). Use emitext_link_feed for the writes. */
#define EMITEXT_BLE_SERVICE_UUID "6d696e65-6d69-4000-8000-656d69746578"
#define EMITEXT_BLE_RX_UUID "6d696e65-6d69-4001-8000-656d69746578"
#define EMITEXT_BLE_TX_UUID "6d696e65-6d69-4002-8000-656d69746578"
#define EMITEXT_BLE_DEFAULT_MTU 20 /* ATT_MTU 23 - 3, what a peer which did not negotiate gets */
#define EMITEXT_USB_FULL_SPEED_MTU 64
#define EMITEXT_USB_HIGH_SPEED_MTU 512

/* ---- one request ------------------------------------------------------------------------------------------------ */

typedef struct EmiTextReq {
    EmiHttpdMethod method; /* 0 for `routes` */
    bool routes;           /* the request lists the routes */
    char* path;            /* without the query, percent encoded; points into line */
    char* query;           /* after the '?', or NULL */
    char* body;            /* "" when there is none */
    char id[EMITEXT_ID_MAX + 1];
    char* line;            /* the copy of the line the three above point into (malloc'd) */
    char* frame;           /* the answer, once emitext_reply was called (malloc'd, ends with a newline) */
    size_t frame_len;
    int status;
} EmiTextReq;

static inline void emitext_req_free(EmiTextReq* r) {
    free(r->line);
    free(r->frame);
    memset(r, 0, sizeof(*r));
}

static inline bool emitext_method_from(const char* s, size_t n, EmiHttpdMethod* out) {
    static const struct {
        const char* name;
        EmiHttpdMethod method;
    } names[] = {{"get", EMIHTTPD_GET},       {"post", EMIHTTPD_POST},     {"put", EMIHTTPD_PUT},
                 {"patch", EMIHTTPD_PATCH},   {"delete", EMIHTTPD_DELETE}, {"head", EMIHTTPD_HEAD},
                 {"options", EMIHTTPD_OPTIONS}};
    for (size_t i = 0; i < sizeof(names) / sizeof(names[0]); i++) {
        size_t len = strlen(names[i].name);
        if (len != n) continue;
        size_t k = 0;
        while (k < n && tolower((unsigned char) s[k]) == names[i].name[k]) k++;
        if (k == n) {
            *out = names[i].method;
            return true;
        }
    }
    return false;
}

/* Reads "METHOD[#id] /path?query body" (without the prefix and the newline). 0 on success, else the status to answer
 * with (the id is filled in as far as it was read, so the error can carry it). */
static inline int emitext_parse(const char* text, EmiTextReq* r) {
    memset(r, 0, sizeof(*r));
    r->line = strdup(text);
    if (!r->line) return 500;
    char* p = r->line;
    while (*p == ' ' || *p == '\t') p++;

    char* m = p;
    while (*p && *p != ' ' && *p != '\t' && *p != '#') p++;
    size_t mlen = (size_t) (p - m);
    if (*p == '#') {
        p++;
        size_t n = 0;
        while (*p && *p != ' ' && *p != '\t') {
            if (n < EMITEXT_ID_MAX) r->id[n] = *p;
            n++;
            p++;
        }
        if (n > EMITEXT_ID_MAX) {
            r->id[0] = '\0';
            return 400;
        }
        r->id[n] = '\0';
        for (size_t i = 0; i < n; i++) {
            if (!isalnum((unsigned char) r->id[i]) && r->id[i] != '_' && r->id[i] != '-') {
                r->id[0] = '\0';
                return 400;
            }
        }
    }
    if (mlen == 6 && strncasecmp(m, "routes", 6) == 0) {
        r->routes = true;
        return 0;
    }
    if (!emitext_method_from(m, mlen, &r->method)) return 400;

    while (*p == ' ' || *p == '\t') p++;
    if (*p != '/') return 400;
    r->path = p;
    while (*p && *p != ' ' && *p != '\t') p++;
    bool more = *p != '\0';
    if (more) *p++ = '\0';
    char* q = strchr(r->path, '?');
    if (q) {
        *q = '\0';
        r->query = q + 1;
    }
    while (*p == ' ' || *p == '\t') p++;
    r->body = p;
    return 0;
}

/* Builds the frame ":::STATUS[#id] body\n" of the answer. A newline inside body (json allows them between tokens
 * only) becomes a space, so the frame stays one line. Returns 0, or -1 when out of memory. */
static inline int emitext_reply(EmiTextReq* r, int status, const char* body) {
    free(r->frame);
    size_t blen = body ? strlen(body) : 0;
    size_t cap = strlen(EMITEXT_PREFIX) + 12 + EMITEXT_ID_MAX + 2 + blen + 2;
    char* f = (char*) malloc(cap);
    if (!f) {
        r->frame = NULL;
        r->frame_len = 0;
        return -1;
    }
    int n = snprintf(f, cap, "%s%d", EMITEXT_PREFIX, status);
    if (r->id[0]) n += snprintf(f + n, cap - (size_t) n, "#%s", r->id);
    if (blen) {
        f[n++] = ' ';
        for (size_t i = 0; i < blen; i++) f[n++] = (body[i] == '\n' || body[i] == '\r') ? ' ' : body[i];
    }
    f[n++] = '\n';
    f[n] = '\0';
    r->frame = f;
    r->frame_len = (size_t) n;
    r->status = status;
    return 0;
}

/* ---- a link: bytes in, requests out, frames written back ------------------------------------------------------------ */

typedef int (*EmiTextWrite)(const uint8_t* data, size_t len, void* user);
/* Answers one request: parse already succeeded; call emitext_reply on it (the link writes the frame). */
typedef void (*EmiTextHandler)(EmiTextReq* req, void* user);

typedef struct EmiTextLink {
    EmiTextWrite write;
    void* write_user;
    size_t mtu; /* 0: a frame goes out in one write */
    EmiTextHandler handler;
    void* handler_user;
    char* buf;
    size_t len, cap;
    int state; /* 0 start of a line, 1 not ours, 2 collecting, 3 too long */
    int colons;
} EmiTextLink;

static inline void emitext_link_init(EmiTextLink* l, EmiTextHandler handler, void* handler_user, EmiTextWrite write, void* write_user, size_t mtu) {
    memset(l, 0, sizeof(*l));
    l->handler = handler;
    l->handler_user = handler_user;
    l->write = write;
    l->write_user = write_user;
    l->mtu = mtu;
}

static inline void emitext_link_deinit(EmiTextLink* l) {
    free(l->buf);
    l->buf = NULL;
    l->len = l->cap = 0;
}

/* Writes data in pieces of at most mtu bytes; -1 as soon as the transport refuses a piece. */
static inline int emitext_link_send(EmiTextLink* l, const uint8_t* data, size_t len) {
    if (!l->write) return -1;
    size_t step = l->mtu ? l->mtu : len;
    for (size_t at = 0; at < len; at += step) {
        size_t n = len - at < step ? len - at : step;
        if (l->write(data + at, n, l->write_user) < 0) return -1;
    }
    return 0;
}

static inline void emitext_link_answer(EmiTextLink* l, int status, const char* id, const char* message) {
    EmiTextReq r;
    memset(&r, 0, sizeof(r));
    if (id) snprintf(r.id, sizeof(r.id), "%s", id);
    char body[160];
    snprintf(body, sizeof(body), "{\"error\":\"%s\"}", message);
    if (emitext_reply(&r, status, body) == 0) emitext_link_send(l, (const uint8_t*) r.frame, r.frame_len);
    emitext_req_free(&r);
}

/* One complete line (no prefix, no newline). */
static inline void emitext_link_line(EmiTextLink* l, const char* text) {
    EmiTextReq r;
    int bad = emitext_parse(text, &r);
    if (bad) {
        emitext_link_answer(l, bad, r.id[0] ? r.id : NULL, bad == 400 ? "unreadable request" : "out of memory");
    } else if (l->handler) {
        l->handler(&r, l->handler_user);
        if (!r.frame) emitext_reply(&r, 500, "{\"error\":\"no answer\"}");
        if (r.frame) emitext_link_send(l, (const uint8_t*) r.frame, r.frame_len);
    }
    emitext_req_free(&r);
}

static inline int emitext_link_push(EmiTextLink* l, char c) {
    if (l->len + 1 >= l->cap) {
        size_t cap = l->cap ? l->cap * 2 : 256;
        if (cap > EMITEXT_MAX_LINE + 1) cap = EMITEXT_MAX_LINE + 1;
        if (l->len + 1 >= cap) return -1;
        char* grown = (char*) realloc(l->buf, cap);
        if (!grown) return -1;
        l->buf = grown;
        l->cap = cap;
    }
    l->buf[l->len++] = c;
    l->buf[l->len] = '\0';
    return 0;
}

/* Bytes of a stream (a serial port, a GATT write of any size): requests are found in them and answered as they
 * complete; whatever is not a line starting with ":::" is skipped. Call from the thread which runs the router. */
static inline void emitext_link_feed(EmiTextLink* l, const uint8_t* data, size_t len) {
    const size_t plen = strlen(EMITEXT_PREFIX);
    for (size_t i = 0; i < len; i++) {
        char c = (char) data[i];
        switch (l->state) {
            case 0:
                if (c == EMITEXT_PREFIX[l->colons]) {
                    if ((size_t) ++l->colons == plen) {
                        l->state = 2;
                        l->colons = 0;
                        l->len = 0;
                    }
                } else if (c == '\n') {
                    l->colons = 0;
                } else if (c != '\r' || l->colons) {
                    l->state = 1;
                    l->colons = 0;
                }
                break;
            case 1:
                if (c == '\n') l->state = 0;
                break;
            case 2:
                if (c == '\n') {
                    l->state = 0;
                    emitext_link_line(l, l->len ? l->buf : "");
                    l->len = 0;
                } else if (c != '\r' && emitext_link_push(l, c) != 0) {
                    l->state = 3;
                }
                break;
            default:
                if (c == '\n') {
                    l->state = 0;
                    l->len = 0;
                    emitext_link_answer(l, 413, NULL, "request too long");
                }
                break;
        }
    }
}

/* One whole request which arrived as a unit (a USB bulk transfer, a GATT write of the whole request): the prefix
 * and the newline are optional. */
static inline void emitext_link_message(EmiTextLink* l, const uint8_t* data, size_t len) {
    if (len > EMITEXT_MAX_LINE) {
        emitext_link_answer(l, 413, NULL, "request too long");
        return;
    }
    char* text = (char*) malloc(len + 1);
    if (!text) return;
    memcpy(text, data, len);
    text[len] = '\0';
    char* p = text;
    const size_t plen = strlen(EMITEXT_PREFIX);
    if (strncmp(p, EMITEXT_PREFIX, plen) == 0) p += plen;
    for (size_t n = strlen(p); n > 0 && (p[n - 1] == '\n' || p[n - 1] == '\r' || p[n - 1] == '\0'); n--) p[n - 1] = '\0';
    if (*p) emitext_link_line(l, p);
    free(text);
}

#endif /* EMISDK_EMITEXT_H */
