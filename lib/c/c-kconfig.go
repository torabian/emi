package c

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/torabian/emi/lib/core"
)

var kconfigIdent = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*`)

// kconfigSymbols maps every config name of the module (nested ones included) to its
// Kconfig symbol, so `depends:` can refer to configs by the names used in the yml.
func kconfigSymbols(prefix string, configs []core.EmiConfig, into map[string]string) {
	for _, cfg := range configs {
		sym := kconfigSymbol(prefix, cfg)
		into[cfg.Name] = sym
		kconfigSymbols(sym, cfg.Fields, into)
	}
}

// kconfigSymbol is <PREFIX>_<NAME> (snake upper), unless `env` is set: then env is the
// whole symbol, the same way it overrides the variable name for the Go target.
func kconfigSymbol(prefix string, cfg core.EmiConfig) string {
	if cfg.Env != "" {
		return cfg.Env
	}
	return prefix + "_" + core.ToSnakeUpper(cfg.Name)
}

func kconfigQuote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// kconfigText splits a description into the prompt (first line) and the help (the rest).
func kconfigText(cfg core.EmiConfig) (prompt string, help []string) {
	lines := strings.Split(strings.TrimSpace(cfg.Description), "\n")
	prompt = strings.TrimSpace(lines[0])
	if prompt == "" {
		prompt = cfg.Name
	}
	for _, l := range lines[1:] {
		help = append(help, strings.TrimRight(l, " \t"))
	}
	return prompt, help
}

func kconfigDefault(cfg core.EmiConfig, kind string) (string, error) {
	d := cfg.Default
	switch kind {
	case "bool":
		switch strings.ToLower(d) {
		case "", "false", "n", "no", "0":
			return "n", nil
		case "true", "y", "yes", "1":
			return "y", nil
		}
		return "", fmt.Errorf("config %q: %q is not a bool default", cfg.Name, d)
	case "int":
		if d == "" {
			return "0", nil
		}
		return d, nil
	}
	return kconfigQuote(d), nil
}

func kconfigEntries(sb *strings.Builder, prefix string, configs []core.EmiConfig, symbols map[string]string) error {
	for _, cfg := range configs {
		sym := kconfigSymbol(prefix, cfg)

		if len(cfg.Fields) > 0 {
			prompt, _ := kconfigText(cfg)
			fmt.Fprintf(sb, "menu %s\n\n", kconfigQuote(prompt))
			if err := kconfigEntries(sb, sym, cfg.Fields, symbols); err != nil {
				return err
			}
			sb.WriteString("endmenu\n\n")
			continue
		}

		var kind string
		switch cfg.Type {
		case "", "string":
			kind = "string"
		case "bool", "boolean":
			kind = "bool"
		case "int", "int32", "int64":
			kind = "int"
		default:
			return fmt.Errorf("config %q: type %q has no Kconfig equivalent (use string, bool or int)", cfg.Name, cfg.Type)
		}
		if (cfg.Min != "" || cfg.Max != "") && (kind != "int" || cfg.Min == "" || cfg.Max == "") {
			return fmt.Errorf("config %q: min and max go together and only on an int", cfg.Name)
		}

		prompt, help := kconfigText(cfg)
		def, err := kconfigDefault(cfg, kind)
		if err != nil {
			return err
		}

		fmt.Fprintf(sb, "config %s\n    %s %s\n    default %s\n", sym, kind, kconfigQuote(prompt), def)
		if cfg.Min != "" {
			fmt.Fprintf(sb, "    range %s %s\n", cfg.Min, cfg.Max)
		}
		if cfg.Depends != "" {
			expr := kconfigIdent.ReplaceAllStringFunc(cfg.Depends, func(id string) string {
				if s, ok := symbols[id]; ok {
					return s
				}
				return id
			})
			fmt.Fprintf(sb, "    depends on %s\n", expr)
		}
		if len(help) > 0 {
			sb.WriteString("    help\n")
			for _, l := range help {
				if l == "" {
					sb.WriteString("\n")
				} else {
					fmt.Fprintf(sb, "        %s\n", l)
				}
			}
		}
		sb.WriteString("\n")
	}
	return nil
}

// CKconfigVirtualFile renders the module's `config:` block as Kconfig.<module>: bare
// `config` entries (no mainmenu), meant to be `rsource`d by a Kconfig / Kconfig.projbuild.
// Nil when the module has no config.
func CKconfigVirtualFile(module *core.Emi) (*core.VirtualFile, error) {
	if len(module.Config) == 0 {
		return nil, nil
	}
	name := cIdent(core.ToSnakeCase(module.Name))
	if name == "" {
		name = "module"
	}
	prefix := strings.ToUpper(name)

	symbols := map[string]string{}
	kconfigSymbols(prefix, module.Config, symbols)

	var sb strings.Builder
	sb.WriteString("# Generated by the Emi compiler (--tags kconfig) from the config: block - do not edit by hand.\n")
	fmt.Fprintf(&sb, "# C sees every entry as CONFIG_<symbol> through sdkconfig.h.\n\n")
	if err := kconfigEntries(&sb, prefix, module.Config, symbols); err != nil {
		return nil, err
	}

	return &core.VirtualFile{
		Name:         "Kconfig",
		Extension:    "." + name,
		ActualScript: strings.TrimRight(sb.String(), "\n") + "\n",
	}, nil
}
