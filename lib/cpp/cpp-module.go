// ---- generic dialect: common includes + `#pragma once` wrapping -------------

// An unused #include is never a compiler error in C++, so a single fixed set -
// covering every runtime header any generated dto/action file might need,
// including the ones only an action (never a plain dto) actually uses - is
// simpler and just as correct as computing a precise one per file (same
// reasoning the C target's own commonIncludes documents).
var cppGenericCommonIncludes = []string{
	`"cjson/cJSON.h"`,
	`"EmiJson.hpp"`,
	`"EmiHttpTransport.hpp"`,
	`"EmiByteStream.hpp"`,
	`"EmiWebSocketX.hpp"`,
	"<cstdint>",
	"<map>",
	"<memory>",
	"<optional>",
	"<string>",
	"<utility>",
	"<vector>",
}

// CppGenericAsFullDocument wraps a compiled chunk into a standalone,
// `#pragma once`-guarded .hpp file: the common includes, plus any module-specific
// #include (a sibling generated header, or a resolved complex type's own
// header), then the actual body.
func CppGenericAsFullDocument(x *core.CodeChunkCompiled) string {
	includes := make([]string, len(cppGenericCommonIncludes))
	copy(includes, cppGenericCommonIncludes)
	seen := map[string]struct{}{}
	for _, i := range includes {
		seen[i] = struct{}{}
	}
	for _, dep := range x.CodeChunkDependensies {
		if dep.Location == "" {
			continue
		}
		spelling := dep.Location
		if !strings.HasPrefix(spelling, "<") && !strings.HasPrefix(spelling, `"`) {
			spelling = `"` + spelling + `"`
		}
		if _, ok := seen[spelling]; ok {
			continue
		}
		seen[spelling] = struct{}{}
		includes = append(includes, spelling)
	}

	var sb strings.Builder
	sb.WriteString("// Generated by the Emi compiler - do not edit by hand.\n#pragma once\n\n")
	for _, i := range includes {
		fmt.Fprintf(&sb, "#include %v\n", i)
	}
	sb.WriteString("\n")
	sb.Write(x.ActualScript)

	return string(core.EscapeLines([]byte(sb.String())))
}

// ---- unreal dialect: `#pragma once` + CoreMinimal + trailing .generated.h ---

var cppUnrealCommonIncludes = []string{
	`"CoreMinimal.h"`,
	`"Dom/JsonValue.h"`,
}

// CppUnrealAsFullDocument wraps a compiled chunk into a standalone Unreal header:
// `#pragma once`, CoreMinimal.h + any module-specific #include, the actual body,
// and - critically, and always LAST, per Unreal Header Tool's own requirement -
// `#include "<FileName>.generated.h"`.
