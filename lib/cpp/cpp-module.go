// DiscoverComplexes finds every module-level complex type compiled for this
// dialect, mirroring the same helper in the sibling generators. ImportLocation is
// a #include spelling (generic) or an Unreal header name (unreal).
func DiscoverComplexes(module *core.Emi, dialect Dialect) []RecognizedComplex {
	want := map[Dialect][]string{
		DialectGeneric: {"cpp", "cpp-generic", ""},
		DialectUnreal:  {"cpp", "cpp-unreal", "unreal", ""},
	}[dialect]

	items := []RecognizedComplex{}
	for _, complex := range module.Complexes {
		if slices.Contains(want, complex.Compiler) {
			items = append(items, RecognizedComplex{
				Symbol:         complex.Name,
				ImportLocation: complex.Location,
			})
		}
	}
	return items
}

type CppModuleGenerationFlags struct {
	Actions *string
	Remotes *string
	Dtos    *string
}

func (x CppModuleGenerationFlags) filterList(raw *string) []string {
	if raw == nil || *raw == "" {
		return nil
	}
	return strings.Split(*raw, ",")
}

func readCppModuleFlags(ctx core.MicroGenContext) CppModuleGenerationFlags {
	config := CppModuleGenerationFlags{}
	if v, ok := ctx.Flags["actions"]; ok && v != "" {
		config.Actions = &v
	}
	if v, ok := ctx.Flags["remotes"]; ok && v != "" {
		config.Remotes = &v
	}
	if v, ok := ctx.Flags["dtos"]; ok && v != "" {
		config.Dtos = &v
	}
	return config
}

// CppModuleFullVirtualFiles compiles an entire Emi module into a C++ SDK - one
// header per dto/enum/action/remote, plus the embedded runtime (dialect-
// dependent) and a README, mirroring the equivalent full-module compilers in the
// sibling generators. No server/CLI/entity-persistence code is ever generated
// here - see the lib/cpp package doc comment.
func CppModuleFullVirtualFiles(module *core.Emi, ctx core.MicroGenContext) ([]core.VirtualFile, error) {
	dialect := ResolveDialect(ctx)
	complexes := DiscoverComplexes(module, dialect)
	config := readCppModuleFlags(ctx)
	files := []core.VirtualFile{}

	dtoFilter := config.filterList(config.Dtos)
	actionFilter := config.filterList(config.Actions)
	remoteFilter := config.filterList(config.Remotes)

	asDoc := func(chunk *core.CodeChunkCompiled) string {
		if dialect == DialectUnreal {
			return CppUnrealAsFullDocument(chunk, chunk.SuggestedFileName)
		}
		return CppGenericAsFullDocument(chunk)
	}

	for _, dto := range module.Dto {
		if len(dtoFilter) > 0 && !slices.Contains(dtoFilter, dto.Name) {
			continue
		}
		chunk, err := CppCommonObjectGenerator(dto.Fields, ctx, CppCommonObjectContext{
			Dialect:             dialect,
			RootClassName:       dto.GetClassName(),
			RecognizedComplexes: complexes,
		})
		if err != nil {
			return nil, err
		}
		files = append(files, core.VirtualFile{
			Name:         chunk.SuggestedFileName,
			Extension:    chunk.SuggestedExtension,
			ActualScript: asDoc(chunk),
		})
	}

	for _, enum := range module.Enums {
		chunk, err := CppStandaloneEnum(enum, dialect, ctx)
		if err != nil {
			return nil, err
		}
		files = append(files, core.VirtualFile{
			Name:         chunk.SuggestedFileName,
			Extension:    chunk.SuggestedExtension,
			ActualScript: asDoc(chunk),
		})
	}

	for _, action := range module.Actions {
		if len(actionFilter) > 0 && !slices.Contains(actionFilter, action.Name) {
			continue
		}
		chunk, err := CppActionRender(action, dialect, ctx, complexes)
		if err != nil {
			return nil, err
		}
		if chunk == nil {
			continue
		}
		files = append(files, core.VirtualFile{
			Name:         chunk.SuggestedFileName,
			Extension:    chunk.SuggestedExtension,
			ActualScript: asDoc(chunk),
		})
	}

	for _, remote := range module.Remotes {
		if len(remoteFilter) > 0 && !slices.Contains(remoteFilter, remote.Name) {
			continue
		}
		chunk, err := CppActionRender(remote, dialect, ctx, complexes)
		if err != nil {
			return nil, err
		}
		if chunk == nil {
			continue
		}
		files = append(files, core.VirtualFile{
			Name:         chunk.SuggestedFileName,
			Extension:    chunk.SuggestedExtension,
			ActualScript: asDoc(chunk),
		})
	}

	skipSdk := ctx.HasTag(NoSdk)
	if !skipSdk {
		if dialect == DialectUnreal {
			files = append(files, core.FsEmbedToVirtualFile(&cppIncludeUnreal.Content, "")...)
		} else {
			files = append(files, core.FsEmbedToVirtualFile(&cppIncludeGeneric.Content, "")...)
		}
	}

	skipPackage := ctx.HasTag(NoPackage)
	if !skipPackage {
		readme := cppGenericReadme
		if dialect == DialectUnreal {
			readme = cppUnrealReadme
		}
		files = append(files, core.VirtualFile{
			Name:         "README",
			Extension:    ".md",
			ActualScript: readme,
		})
	}

	return files, nil
}

