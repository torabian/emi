// These cover the exact same MOne (one/one?), MCollection (collection/collection?) and
// MArray (array/array?, including array nested inside object/object? containers)
// scenarios as actions_postgres_test.go, but against a throwaway sqlite file instead of
// a real Postgres instance - no docker-compose, no external service, just `go test`.
//
// This only became possible once uniqueId stopped depending on Postgres's own
// gen_random_uuid() column default (see go-entity-default-fields.go / the BeforeCreate
// hook in go-entity-render.go): sqlite has no dialect equivalent for that function, so
// before that fix AutoMigrate on sqlite either errored outright or silently produced
// empty uniqueIds. The BeforeCreate hook assigns the UUID in Go instead, which works
// identically on every gorm dialect - sqlite included.
//
// entity.emi.yml's own comments walk through each field's yaml declaration; this file's
// comments instead point at the generated Go shape each relation type produces, since
// that's what the payloads below are built against. See ../../../README or
// entity_sqlite_results.md (generated by this file, see the last test below) for the
// human-readable "yaml in, payload in" pairing the task asked for.

// openSqliteTestDB opens a fresh, empty sqlite database file inside t.TempDir() (removed
// automatically once the test finishes) and auto-migrates every table these tests touch.
// Mirrors openPostgresTestDB in actions_postgres_test.go, minus the docker dependency.
func openSqliteTestDB(t *testing.T) *gorm.DB {
	t.Helper()

	dbPath := filepath.Join(t.TempDir(), "entity.sqlite")
	db, err := gorm.Open(sqlite.Open(dbPath), &gorm.Config{Logger: logger.Default.LogMode(logger.Warn)})
	if err != nil {
		t.Fatalf("failed to open sqlite db at %s: %v", dbPath, err)
	}

	// gorm's AutoMigrate does not auto-discover has-many child row types through an
	// association field (Entity1Entity.Items) - each has to be listed explicitly, or
	// their tables never get created. This includes relations nested inside
	// object/object? containers (NestedContainer.NestedInner.NestedItems and friends).
	if err := db.AutoMigrate(
		&Entity2Entity{},
		&Entity1Entity{},
		&Entity1EntityItems{},
		&Entity1EntityItems2{},
		&Entity1EntityItemsSubItems{},
		&Entity1EntityItemsSubItemsSubSubItems{},
		&Entity1EntityNestedContainerNestedInnerNestedItems{},
		&Entity1EntityNestedContainerOptNestedInnerNestedItemsOpt{},
	); err != nil {
		t.Fatalf("AutoMigrate error: %v", err)
	}

	return db
}

// TestSqlite_AutoMigrateProducesExpectedSchema is the sqlite counterpart of
// runAutoMigrateAssertions (migrate_shared_test.go) - it needs a real Postgres/MySQL
// instance behind the `integration` build tag, this doesn't need anything at all.
func TestSqlite_AutoMigrateProducesExpectedSchema(t *testing.T) {
	db := openSqliteTestDB(t)
	m := db.Migrator()

	t.Run("one/one? produced real FK columns, not the DTO wrapper", func(t *testing.T) {
		if !m.HasColumn(&Entity1Entity{}, "OwnerId") {
			t.Error("expected OwnerId FK column on entity1_table")
		}
		if !m.HasColumn(&Entity1Entity{}, "ManagerId") {
			t.Error("expected ManagerId FK column on entity1_table")
		}
		if m.HasColumn(&Entity1Entity{}, "Owner") {
			t.Error("did not expect a column for the Owner DTO field itself (gorm:\"-\")")
		}
	})

	t.Run("array/array? produced real has-many child tables with LinkerId", func(t *testing.T) {
		if !m.HasTable(&Entity1EntityItems{}) {
			t.Error("expected a table for Entity1EntityItems (has-many child rows)")
		}
		if !m.HasColumn(&Entity1EntityItems{}, "LinkerId") {
			t.Error("expected LinkerId FK column on the Entity1EntityItems child table")
		}
		if !m.HasTable(&Entity1EntityItems2{}) {
			t.Error("expected a table for Entity1EntityItems2 (has-many child rows)")
		}
	})

	t.Run("collection/collection? produced a many2many join table", func(t *testing.T) {
		if !m.HasTable("entity1_items3") {
			t.Error("expected join table entity1_items3 for the Items3 many2many relation")
		}
		if !m.HasTable("entity1_items4") {
			t.Error("expected join table entity1_items4 for the Items4 many2many relation")
		}
	})

	t.Run("array nested 2 objects deep still produced its own child table", func(t *testing.T) {
		if !m.HasTable(&Entity1EntityNestedContainerNestedInnerNestedItems{}) {
			t.Error("expected a table for the nested has-many child rows (NestedContainer.NestedInner.NestedItems)")
		}
	})
}

// TestSqlite_OneField_CreateResolvesOwnerAndPersistsForeignKey covers a plain "one"
// (MOne, required) field end to end via Entity1EntityActions.Create: entity1.owner ->
// Entity2Entity, wired through the generated OwnerId column.
func TestSqlite_OneField_CreateResolvesOwnerAndPersistsForeignKey(t *testing.T) {
	db := openSqliteTestDB(t)

	owner := &Entity2Entity{UniqueId: "owner-1", Label2: "owner-one"}
	if err := db.Create(owner).Error; err != nil {
		t.Fatalf("seed owner error: %v", err)
	}

	dto := &Entity1Entity{Title: "hello", IsActive: true, Owner: owner}
	created, err := Entity1EntityActions.Create(db, dto)
	if err != nil {
		t.Fatalf("Create error: %v", err)
	}
	if created.UniqueId == "" {
		t.Fatal("expected BeforeCreate to assign a UniqueId (no gen_random_uuid() on sqlite)")
	}

	var reloaded Entity1Entity
	if err := db.Preload("Owner").First(&reloaded, "unique_id = ?", created.UniqueId).Error; err != nil {
		t.Fatalf("reload error: %v", err)
	}
	if reloaded.Owner == nil || reloaded.Owner.Label2 != "owner-one" {
		t.Fatalf("expected owner to resolve to owner-one, got %+v", reloaded.Owner)
	}
	if reloaded.OwnerId != owner.Id {
		t.Fatalf("expected OwnerId = owner.Id (%d), got %d", owner.Id, reloaded.OwnerId)
	}
}

