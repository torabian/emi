// TestSqlite_ArrayInsideArray_DeleteRemovesOnlySelectedItems covers the "delete"
// operation (see emigorm.ReconcileHasMany) on an array nested inside another array -
// items[].subItems[].subSubItems[], 3 levels deep (entity.emi.yml's own "items" field).
// It creates a single top-level item with 5 subItems, two of them (sub-2 and sub-3)
// carrying their own subSubItems, then updates with a "delete" selector naming sub-2
// and sub-4 by uniqueId - the same delete works at any nesting depth, not just the top
// level: buildArrayItemFields (lib/golang/go-entity-actions.go) recurses into an
// array's own nested array fields, generating the identical reconcile call one level
// down, however deep the schema goes. sub-2 being deleted while carrying its own
// subSubItems also proves the delete doesn't leave grandchild orphans behind:
// emigorm.ReconcileHasMany's "delete" branch reuses the same
// Select(clause.Associations).Delete(&existing) gorm already uses for "replace"'s own
// orphan cleanup, which cascades through has-many children exactly the same way.
func TestSqlite_ArrayInsideArray_DeleteRemovesOnlySelectedItems(t *testing.T) {
	db := openSqliteTestDB(t)

	subItems := make([]Entity1OptionalDtoItemsSubItems, 5)
	for i := range subItems {
		subItems[i] = Entity1OptionalDtoItemsSubItems{
			SubLabel: fmt.Sprintf("sub-%d", i+1),
		}
	}
	// sub-2 (index 1, about to be deleted) and sub-3 (index 2, kept) both carry their
	// own subSubItems - proves level-3 (the deepest array in this schema) is created
	// correctly via plain gorm cascade on Create, and lets the delete assertions below
	// distinguish "cascaded away with its deleted parent" from "survived untouched".
	subItems[1].SubSubItems = emigo.ArrayNullableReplace([]Entity1OptionalDtoItemsSubItemsSubSubItems{
		{LeafLabel: "leaf-deleted-with-sub-2"},
	})
	subItems[2].SubSubItems = emigo.ArrayNullableReplace([]Entity1OptionalDtoItemsSubItemsSubSubItems{
		{LeafLabel: "leaf-kept-on-sub-3"},
	})

	dto := &Entity1Entity{
		Title: "hello",
		Items: []*Entity1EntityItems{
			{Item2: "parent-item"},
		},
	}
	created, err := Entity1EntityActions.Create(db, dto)
	if err != nil {
		t.Fatalf("Create error: %v", err)
	}

	// entity1's own Create path (Entity1EntityCreateFn) takes the entity struct
	// directly and relies on gorm's automatic cascade for array children (see
	// walkCreateFields's own comment) - which does not run the Operation-wrapped
	// dto conversion buildArrayItemFields generates for Update. So the 5 subItems
	// (level 2, needed to exercise "delete" against) are seeded via a real Update
	// "replace" first, exactly the way a caller would populate them through the API.
	var seed Entity1OptionalDto
	seed.Items.Set("replace", []Entity1OptionalDtoItems{
		{UniqueId: emigo.NullableOf(created.Items[0].UniqueId), Item2: "parent-item", SubItems: emigo.ArrayNullableReplace(subItems)},
	})
	if _, err := Entity1EntityActions.Update(db, created.UniqueId, seed); err != nil {
		t.Fatalf("seed Update error: %v", err)
	}

	var afterSeed Entity1Entity
	if err := db.Preload("Items.SubItems.SubSubItems").
		First(&afterSeed, "unique_id = ?", created.UniqueId).Error; err != nil {
		t.Fatalf("reload after seed error: %v", err)
	}
	if len(afterSeed.Items) != 1 || len(afterSeed.Items[0].SubItems) != 5 {
		t.Fatalf("expected 1 item with 5 subItems after seeding, got %+v", afterSeed.Items)
	}
	leaf := afterSeed.Items[0]
	var toDelete []string
	for _, si := range leaf.SubItems {
		if si.SubLabel == "sub-2" || si.SubLabel == "sub-4" {
			toDelete = append(toDelete, si.UniqueId)
		}
	}
	if len(toDelete) != 2 {
		t.Fatalf("expected to find sub-2 and sub-4 among the seeded subItems, got %+v", leaf.SubItems)
	}
	// sub-2 and sub-3's own subSubItems must have made it through the cascade create.
	var sub2Leaf, sub3Leaf string
	for _, si := range leaf.SubItems {
		switch si.SubLabel {
		case "sub-2":
			if len(si.SubSubItems) == 1 {
				sub2Leaf = si.SubSubItems[0].LeafLabel
			}
		case "sub-3":
			if len(si.SubSubItems) == 1 {
				sub3Leaf = si.SubSubItems[0].LeafLabel
			}
		}
	}
	if sub2Leaf != "leaf-deleted-with-sub-2" || sub3Leaf != "leaf-kept-on-sub-3" {
		t.Fatalf("expected sub-2/sub-3 to each carry their own subSubItems leaf, got %+v", leaf.SubItems)
	}

	// The actual delete: a plain {"uniqueId": "..."} per row is all "delete" ever
	// reads (see emigo.Array's own doc comment / emigorm.ReconcileHasMany) - no
	// other field needs to be sent.
	deleteItems := make([]Entity1OptionalDtoItemsSubItems, len(toDelete))
	for i, uid := range toDelete {
		deleteItems[i] = Entity1OptionalDtoItemsSubItems{UniqueId: emigo.NullableOf(uid)}
	}

	var input Entity1OptionalDto
	input.Items.Set("replace", []Entity1OptionalDtoItems{
		{UniqueId: emigo.NullableOf(created.Items[0].UniqueId), Item2: "parent-item", SubItems: emigo.ArrayNullableDelete(deleteItems)},
	})
	if _, err := Entity1EntityActions.Update(db, created.UniqueId, input); err != nil {
		t.Fatalf("delete Update error: %v", err)
	}

	var afterDelete Entity1Entity
	if err := db.Preload("Items.SubItems.SubSubItems").
		First(&afterDelete, "unique_id = ?", created.UniqueId).Error; err != nil {
		t.Fatalf("reload after delete error: %v", err)
	}
	remaining := afterDelete.Items[0].SubItems
	if len(remaining) != 3 {
		t.Fatalf("expected 3 subItems to remain after deleting 2 of 5, got %d: %+v", len(remaining), remaining)
	}
	byLabel := map[string]bool{}
	for _, si := range remaining {
		byLabel[si.SubLabel] = true
	}
	if byLabel["sub-2"] || byLabel["sub-4"] {
		t.Fatalf("expected sub-2 and sub-4 to be gone, got %+v", remaining)
	}
	if !byLabel["sub-1"] || !byLabel["sub-3"] || !byLabel["sub-5"] {
		t.Fatalf("expected sub-1, sub-3 and sub-5 to still be present, got %+v", remaining)
	}

	// sub-2/sub-4 must be actually gone, not just orphaned.
	var deletedCheck []Entity1EntityItemsSubItems
	db.Unscoped().Where("unique_id IN ?", toDelete).Find(&deletedCheck)
	if len(deletedCheck) != 0 {
		t.Fatalf("expected sub-2/sub-4 rows to be hard-deleted, found %d", len(deletedCheck))
	}

	// sub-2's own subSubItems row (leaf-deleted-with-sub-2) must have cascaded away
	// with it - a level-3 orphan left behind would be exactly the bug this test
	// exists to catch.
	var orphanCheck []Entity1EntityItemsSubItemsSubSubItems
	db.Unscoped().Where("leaf_label = ?", "leaf-deleted-with-sub-2").Find(&orphanCheck)
	if len(orphanCheck) != 0 {
		t.Fatalf("expected sub-2's own subSubItems row to be gone along with it, found %d orphan(s)", len(orphanCheck))
	}

	// sub-3 (never touched by the delete) must still carry its own subSubItems leaf -
	// deleting sibling subItems must never disturb an untouched one's own children.
	for _, si := range remaining {
		if si.SubLabel == "sub-3" {
			if len(si.SubSubItems) != 1 || si.SubSubItems[0].LeafLabel != "leaf-kept-on-sub-3" {
				t.Fatalf("expected sub-3 to still carry leaf-kept-on-sub-3, got %+v", si.SubSubItems)
			}
		}
	}
}
