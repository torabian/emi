/*
 * EmiMediaFrame - the tiny per-frame header used to multiplex microphone and
 * camera data over ONE binary WebSocket (a `method: reactive` action with
 * `binaryType: arraybuffer`). The Go twin is emigo.MediaFrame (emigo/MediaFrame.go);
 * both sides must agree on this layout:
 *
 *    offset  size  field
 *      0      1    kind       1 = audio, 2 = video, 3 = metadata/other
 *      1      1    flags      bit0 = keyframe / start of a new audio packet burst
 *      2      2    reserved   always 0
 *      4      4    seq        per-kind counter, big endian (gap = lost/dropped frame)
 *      8      4    timestamp  milliseconds since the stream started, big endian
 *     12      n    payload    codec bytes exactly as produced (PCM16LE, Opus, JPEG, H.264 ...)
 *
 * The codec itself is NOT repeated per frame: it is announced once through the
 * action's typed query parameters (sampleRate, audioCodec, videoCodec ...).
 *
 * Generated by the Emi compiler - do not edit by hand.
 */
#pragma once

#include "EmiWebSocketX.hpp"

#include <cstddef>
#include <cstdint>

namespace emi {

enum EmiMediaKind : uint8_t { EmiMediaAudio = 1, EmiMediaVideo = 2, EmiMediaOther = 3 };
enum EmiMediaFlags : uint8_t { EmiMediaKeyframe = 0x01 };

constexpr size_t kEmiMediaFrameHeaderSize = 12;

struct EmiMediaFrameHeader {
    uint8_t kind = EmiMediaAudio;
    uint8_t flags = 0;
    uint32_t seq = 0;
    uint32_t timestampMs = 0;

    void Write(uint8_t out[kEmiMediaFrameHeaderSize]) const {
        out[0] = kind;
        out[1] = flags;
        out[2] = 0;
        out[3] = 0;
        for (int i = 0; i < 4; i++) out[4 + i] = (uint8_t) (seq >> (8 * (3 - i)));
        for (int i = 0; i < 4; i++) out[8 + i] = (uint8_t) (timestampMs >> (8 * (3 - i)));
    }

    // Returns false when `length` is too short to hold a header.
    static bool Read(const uint8_t* data, size_t length, EmiMediaFrameHeader& out) {
        if (length < kEmiMediaFrameHeaderSize) return false;
        out.kind = data[0];
        out.flags = data[1];
        out.seq = 0;
        out.timestampMs = 0;
        for (int i = 0; i < 4; i++) out.seq = (out.seq << 8) | data[4 + i];
        for (int i = 0; i < 4; i++) out.timestampMs = (out.timestampMs << 8) | data[8 + i];
        return true;
    }
};

// Sends one media frame. The header and the payload go out as a single binary
// WebSocket frame without being copied together first, so `payload` can point
// straight at an esp_camera frame buffer or an I2S read buffer.
inline bool EmiSendMediaFrame(EmiWebSocketX& socket, const EmiMediaFrameHeader& header,
                              const uint8_t* payload, size_t length) {
    uint8_t prefix[kEmiMediaFrameHeaderSize];
    header.Write(prefix);
    return socket.SendBinary(prefix, sizeof(prefix), payload, length);
}

// Numbers frames per kind so the receiver can detect drops. Not thread safe -
// use one per sending task, or guard it.
class EmiMediaSender {
public:
    explicit EmiMediaSender(EmiWebSocketX& socket) : socket_(socket) {}

    bool SendAudio(const uint8_t* data, size_t length, uint32_t timestampMs) {
        return Send(EmiMediaAudio, 0, audioSeq_++, timestampMs, data, length);
    }

    bool SendVideo(const uint8_t* data, size_t length, uint32_t timestampMs, bool keyframe = true) {
        return Send(EmiMediaVideo, keyframe ? (uint8_t) EmiMediaKeyframe : (uint8_t) 0, videoSeq_++, timestampMs, data, length);
    }

private:
    bool Send(uint8_t kind, uint8_t flags, uint32_t seq, uint32_t timestampMs, const uint8_t* data, size_t length) {
        EmiMediaFrameHeader header;
        header.kind = kind;
        header.flags = flags;
        header.seq = seq;
        header.timestampMs = timestampMs;
        return EmiSendMediaFrame(socket_, header, data, length);
    }

    EmiWebSocketX& socket_;
    uint32_t audioSeq_ = 0;
    uint32_t videoSeq_ = 0;
};

} // namespace emi
